"""Write docs/codebook.md: every raw answer, what it was recoded to, and how often.

The codebook is generated from the same rules the analysis uses (recode.py),
so it cannot drift out of date. Raw answers are shown with questionnaire
routing notes removed, with counts by survey wave.

Run from the repository root:  python -m src.codebook
"""

from __future__ import annotations

import pandas as pd

from src import recode
from src.build_sample import load_wave
from src.config import ROOT, WAVES

CODEBOOK_PATH = ROOT / "docs" / "codebook.md"

# (raw column, analysis variable, description, rules, default label)
VARIABLES = [
    (
        "political_party",
        "party",
        "Party identification (outcome: DPP = 1, KMT = 0, others excluded)",
        recode.PARTY_RULES,
        "Other or none",
    ),
    (
        "taiwanese_or_chinese",
        "identity",
        "National self-identification",
        recode.IDENTITY_RULES,
        "Other or no answer",
    ),
    (
        "taiwan_indep",
        "independence",
        "Preferred future of cross-Strait relations",
        recode.INDEPENDENCE_RULES,
        "No answer",
    ),
    (
        "pre_ele_101",
        "vote_2012",
        "Vote in the January 2012 presidential election",
        recode.VOTE_2012_RULES,
        "No answer",
    ),
    (
        "pre_ele_97",
        "vote_2008",
        "Vote in the 2008 presidential election (2014 wave: referendum "
        'ballot question, recoded to "Not asked"; not used in the analysis)',
        recode.VOTE_2008_RULES,
        "No answer",
    ),
    ("edu", "education", "Highest level of education", recode.EDUCATION_RULES, "Other"),
    ("marriage", "marital_status", "Marital status", recode.MARRIAGE_RULES, "Other"),
]


def crosswalk(
    raw_column: str, rules: recode.Rules, default: str, waves: tuple[int, ...] = WAVES
) -> pd.DataFrame:
    frames = []
    for year in waves:
        wave = load_wave(year)
        answers = wave[raw_column].map(recode.strip_routing).fillna("(missing)")
        frames.append(pd.DataFrame({"raw": answers, "wave": year}))
    data = pd.concat(frames, ignore_index=True)
    counts = data.pivot_table(index="raw", columns="wave", aggfunc="size", fill_value=0)
    counts = counts.reindex(columns=list(waves), fill_value=0)
    counts.insert(
        0, "recoded", recode.apply_rules(pd.Series(counts.index), rules, default).to_numpy()
    )
    return counts.reset_index().sort_values(["recoded", "raw"])


def markdown_table(table: pd.DataFrame) -> list[str]:
    waves = [str(column) for column in table.columns[2:]]
    lines = ["| Raw answer | Recoded | " + " | ".join(waves) + " |"]
    lines.append("| --- | --- |" + " ---: |" * len(waves))
    for row in table.itertuples(index=False):
        counts = " | ".join(f"{value:,}" for value in row[2:])
        lines.append(f"| {row.raw} | {row.recoded} | {counts} |")
    return lines


def main() -> None:
    lines = [
        "# Codebook",
        "",
        "Generated by `python -m src.codebook` from the rules in `src/recode.py`. Each table lists every",
        'raw answer in the survey extracts (questionnaire routing notes such as "(跳答h7)" removed),',
        "the category it is recoded to, and its count in each wave. Rules are applied in order and the",
        "first match wins, so these tables are the complete record of how answers were coded.",
        "",
        "## Derived numeric variables",
        "",
        "- `age`: survey year minus birth year. Birth year is recorded in the ROC calendar",
        "  (ROC year + 1911 = Gregorian year). Two 2014 respondents with unknown birth year are dropped.",
        "- `female`: 1 if gender is 女 or 女性.",
        "- `income_personal`, `income_household`: monthly income bracket midpoints in NT$10,000",
        '  ("2-3萬元以下" = 2.5; "1萬元以下" = 0.5; open top brackets = 1.25 times the floor;',
        '  no job or no income = 0). Refusals and "don\'t know" are set to 0 in the models and flagged by',
        "  `income_personal_missing` / `income_household_missing`.",
        "- `leaner`: 1 if the party answer is 泛藍 (leans KMT) or 泛綠 (leans DPP), offered only in 2013",
        "  and 2014.",
        "",
    ]
    for raw_column, variable, description, rules, default in VARIABLES:
        lines += [f"## `{variable}`: {description}", "", f"Source column: `{raw_column}`", ""]
        if variable == "vote_2008":
            # 2014 reuses the column for a referendum-ballot question.
            lines += markdown_table(crosswalk(raw_column, rules, default, waves=(2012, 2013)))
            answers = load_wave(2014)[raw_column].map(recode.strip_routing).value_counts()
            listed = ", ".join(f"{answer} ({count:,})" for answer, count in answers.items())
            lines += ["", f'2014 answers to this column, all recoded to "Not asked": {listed}.']
        else:
            lines += markdown_table(crosswalk(raw_column, rules, default))
        lines.append("")
    CODEBOOK_PATH.parent.mkdir(parents=True, exist_ok=True)
    CODEBOOK_PATH.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {CODEBOOK_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
